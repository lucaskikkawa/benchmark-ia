"""Avaliador independente: rubrica com 2 juízes neutros (≠ autora da tarefa, ≠ resolvedora), código anonimizado.
Grava avaliacao_avaliador.json (não toca avaliacao.json nem resultado.json). Timeout = nota 0 sem juiz.
Uso: python scripts/avaliador.py [-j 9] [--refazer] [pastas run-N ...]  (sem pastas: todas exceto grok-4.7-high/_*/piloto)"""
import json, pathlib, re, subprocess, sys, tempfile, shutil, os, signal, threading, time
from concurrent.futures import ThreadPoolExecutor
import yaml
ROOT = pathlib.Path(__file__).resolve().parent.parent
RES = ROOT / "resultados"
sys.path.insert(0, str(ROOT / "scripts"))
from julgar import itens_rubrica
JUIZ_MODELO = {"codex": "gpt-6-luna", "claude": "claude-haiku-5-5", "gemini": "gemini-3.8-flash", "grok": "grok-4.7-build-fast"}
TIMEOUT = 240
JULGAR_TIMEOUT = "--julgar-timeout" in sys.argv
SAIDA = sys.argv[sys.argv.index("--saida") + 1] if "--saida" in sys.argv else "avaliacao_avaliador.json"  # grok-4.7-high: entrega parcial após 900 s é julgada
MARCAS = r"claude|anthropic|opus|haiku|sonnet|gpt[-\w.]*|codex|openai|chatgpt|gemini[-\w.]*|google|bard|antigravity|grok[-\w.]*|xai|x\.ai"
SEM = {e: threading.Semaphore(5) for e in JUIZ_MODELO}
LOG = RES / "_avaliador" / "avaliador.log"; LOG.parent.mkdir(exist_ok=True)

def log(*a):
    with open(LOG, "a") as f: print(time.strftime("%H:%M:%S"), *a, file=f, flush=True)

def anonimizar(rdir):
    codigo = ""
    for p in sorted((rdir / "codigo").rglob("*")):
        if not p.is_file() or "__pycache__" in p.parts or p.name == "enunciado.md":
            continue
        if p.suffix not in (".py", ".md", ".txt", ".toml", ".yaml", ".yml", ".json", ".cfg", ".ini", ""):
            continue
        src = p.read_text(errors="replace")
        src = re.sub(r"(?im)^.*\b(gerad[oa] por|written by|generated by|created by|autor:|author:).*$", "", src)
        src = re.sub(rf"(?i)\b({MARCAS})\b", "[anon]", src)
        src = re.sub(r"/(tmp|workspace|home)/[^\s'\"]*", "[caminho]", src)
        codigo += f"\n### {p.relative_to(rdir / 'codigo')}\n```\n{src[:20000]}\n```\n"
    return codigo or "\n(nenhum arquivo entregue)\n"

def cmd_juiz(emp, prompt):
    m = JUIZ_MODELO[emp]
    if emp == "codex":
        return ["codex", "exec", "--skip-git-repo-check", "-s", "read-only", "-m", m, "-c", "model_reasoning_effort=medium", prompt]
    if emp == "claude":
        return ["claude", "-p", prompt, "--model", m, "--effort", "medium"]
    if emp == "gemini":
        return ["agy", "-p", prompt, "--model", f"{m}-medium"]
    return ["grok", "-p", prompt, "-m", m, "--effort", "medium"]

def chamar(emp, prompt):
    wd = tempfile.mkdtemp(prefix="juiz-")
    try:
        with SEM[emp]:
            p = subprocess.Popen(cmd_juiz(emp, prompt), cwd=wd, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                                 text=True, start_new_session=True, stdin=subprocess.DEVNULL)
            try:
                out, err = p.communicate(timeout=TIMEOUT)
            except subprocess.TimeoutExpired:
                os.killpg(p.pid, signal.SIGKILL); p.communicate(); return None, "timeout"
        return out, (None if p.returncode == 0 else f"exit {p.returncode}: {err[-200:]}")
    finally:
        shutil.rmtree(wd, ignore_errors=True)

def parse(out, ids):
    for m in reversed(re.findall(r"\{[^{}]*\}", out or "", re.S)):
        try: d = json.loads(m)
        except ValueError: continue
        if all(i in d for i in ids):
            try:
                return {i: min(2.0, max(0.0, float(d[i]))) for i in ids}, str(d.get("justificativa", ""))[:400]
            except (TypeError, ValueError): continue
    return None, None

def avaliar(rdir, refazer=False):
    dest = rdir / SAIDA
    if dest.exists() and not refazer:
        old = json.load(open(dest))
        if (old.get("status") == "timeout" and not JULGAR_TIMEOUT) or len([j for j in old["juizes"].values() if j["itens"]]) == 2:
            return
    r = json.load(open(rdir / "resultado.json"))
    tarefa = ROOT / "tarefas" / r["tarefa"]
    meta = yaml.safe_load(open(tarefa / "meta.yaml"))
    autora = meta.get("autor")
    rub_txt = (tarefa / "rubrica.yaml").read_text()
    ids = itens_rubrica(yaml.safe_load(rub_txt))
    neutros = [e for e in JUIZ_MODELO if e not in (autora, r["empresa"])]
    pct = r["pct_passados"]
    av = {"pasta": str(rdir.relative_to(ROOT)), "empresa": r["empresa"], "modelo": r["modelo"], "esforco": r["esforco"],
          "tarefa": r["tarefa"], "tipo": meta.get("tipo"), "run": r["run"], "consistencia_extra": r["run"] > 1,
          "autora_tarefa": autora, "status": r["status"], "duracao_agente_s": r.get("duracao_agente_s"),
          "testes_passados": r["testes_passados"], "testes_total": r["testes_total"], "pct_testes": round(pct, 2),
          "juizes_neutros_elegiveis": neutros, "juizes": {}, "obs": []}
    if meta.get("tipo", "").startswith("08"):
        av["obs"].append("tipo 08: % de testes = % de mutantes mortos pela suíte do agente (mutation testing com mutantes plantados nos testes ocultos)")
    if r["status"] == "timeout" and not JULGAR_TIMEOUT:
        av.update(rubrica_media_10=None, nota_final_10=0.0)
        av["obs"].append("timeout: nota 0 (rubrica não julgada)")
    else:
        extra = ("\nATENÇÃO: o item de documentação deve conferir se SUPOSICOES.md existe e documenta as decisões tomadas nos pontos ambíguos."
                 if meta.get("tipo", "").startswith("10") else "")
        if meta.get("tipo", "").startswith("08"):
            extra = "\nNesta tarefa a solução é uma suíte de testes; avalie a qualidade do código de teste entregue."
        prompt = (f"Você é avaliador de código, cego quanto à autoria. Enunciado da tarefa:\n{(tarefa / 'enunciado.md').read_text()}\n"
                  f"Rubrica (5 itens, cada um 0, 1 ou 2; avalie o CÓDIGO entregue, não testes ocultos):\n{rub_txt}{extra}\n"
                  f"Solução anônima:{anonimizar(rdir)}\n"
                  f"Não use ferramentas nem rode nada. Responda APENAS um JSON numa única linha, sem chaves aninhadas, com as chaves "
                  f"{ids} (valores 0, 1 ou 2) e \"justificativa\" (string curta em português, até 200 caracteres, sem chaves).")
        for j in neutros:
            itens = just = None; erros = []
            for t in (1, 2):
                out, err = chamar(j, prompt)
                itens, just = parse(out, ids)
                if itens: break
                erros.append(f"tentativa {t}: {err or 'JSON inválido'}")
            av["juizes"][j] = {"modelo": JUIZ_MODELO[j], "itens": itens, "rubrica_10": sum(itens.values()) if itens else None,
                               "justificativa": just, "falhas": erros}
            if not itens: av["obs"].append(f"juiz {j} sem resposta válida ({'; '.join(erros)})")
        v = [x["rubrica_10"] for x in av["juizes"].values() if x["rubrica_10"] is not None]
        if len(v) == 1: av["obs"].append("só 1 juiz neutro válido; usada só a nota dele")
        av["rubrica_media_10"] = round(sum(v) / len(v), 2) if v else None
        av["nota_final_10"] = round(0.7 * pct / 10 + 0.3 * av["rubrica_media_10"], 2) if v else None
        if not v: av["obs"].append("nenhum juiz neutro válido: nota pendente")
    json.dump(av, open(dest, "w"), ensure_ascii=False, indent=1)
    log(av["pasta"], av["status"], av.get("rubrica_media_10"), av["nota_final_10"], av["obs"])

def alvos():
    for r in sorted(RES.glob("*/*/*/run-*/resultado.json")):
        rel = r.relative_to(RES).parts
        if rel[0].startswith("_") or rel[0] == "piloto" or rel[1] == "grok-4.7-high": continue
        yield r.parent

if __name__ == "__main__":
    a = sys.argv[1:]
    j = int(a[a.index("-j") + 1]) if "-j" in a else 9
    pastas = [pathlib.Path(x).resolve() for x in a if (x.startswith("/") or x.startswith("resultados")) and x != SAIDA] or list(alvos())
    with ThreadPoolExecutor(j) as ex:
        for f in [ex.submit(avaliar, p, "--refazer" in a) for p in pastas]:
            try: f.result()
            except Exception as e: log("ERRO", repr(e))
    log("FIM", len(pastas))
